# ruff: noqa: E501 — the module is mostly an embedded bash template; line length
# is governed by the generated shell script, not Python style.
"""Generate the standalone shared ``clive`` consumer launcher.

Plain ``clive`` discovers releases from one anonymous site catalog and points
Claude Code or Codex back at that same origin. The explicit ``--openrouter``
mode remains an isolated opt-in; catalog failure never enters it.
"""

from __future__ import annotations

import shlex
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from imas_ambix.agent.profile import SiteConfig


def generate_clive_script(
    site: SiteConfig, *, openrouter_native_release: str | None = None
) -> str:
    """Render a launcher with its site origin and optional proxy alias embedded."""
    from imas_ambix.agent.litellm_service import LITELLM_PORT

    origin = site.global_origin
    proxy_native_release = openrouter_native_release or ""
    template = r"""#!/usr/bin/env bash
# clive — drive an agent CLI against the site model catalog.
#
# GENERATED by the Ambix operator tooling. Do not edit in place; update the
# generator and deploy it again.
#
# Usage:
#   clive [--claude|--codex] [--openrouter] [--list]
#         [--selector RELEASE[@NxFAMILY]|--model RELEASE] [agent-args...]

set -euo pipefail

GLOBAL_ORIGIN=__GLOBAL_ORIGIN__
OPENROUTER_NATIVE_RELEASE=__OPENROUTER_NATIVE_RELEASE__
CLIVE_OPENROUTER="${CLIVE_OPENROUTER:-0}"
LITELLM_PORT="__LITELLM_PORT__"
LITELLM_SERVICE="imas-ambix-llm.service"
HARNESS="claude"
SELECTOR=""
LIST_ONLY=false

usage() {
    cat >&2 <<'USAGE'
clive — drive an agent CLI against the site model catalog.

  clive [--claude|--codex] [--openrouter] [--list]
        [--selector RELEASE[@NxFAMILY]|--model RELEASE] [agent-args...]

  --claude   Claude Code via the Anthropic Messages API (default).
  --codex    OpenAI Codex CLI via the OpenAI API.
  --openrouter
             Explicitly start the per-user proxy after global selection.
  --list     List the global catalog and exit.
  --selector RELEASE[@NxFAMILY]
             Select an exact release id or release-at-topology label.
  --model RELEASE
             Alias for selecting an exact release id.
USAGE
}

ARGS=()
while [[ $# -gt 0 ]]; do
    case "$1" in
        --claude) HARNESS="claude"; shift ;;
        --codex) HARNESS="codex"; shift ;;
        --openrouter) CLIVE_OPENROUTER=1; shift ;;
        --list) LIST_ONLY=true; shift ;;
        --selector|--model)
            [[ $# -ge 2 ]] || { echo "clive: $1 requires a value." >&2; exit 2; }
            [[ -z "$SELECTOR" ]] || { echo "clive: select a model only once." >&2; exit 2; }
            SELECTOR="$2"; shift 2 ;;
        -h|--help) usage; exit 0 ;;
        --) shift; ARGS+=("$@"); break ;;
        *) ARGS+=("$1"); shift ;;
    esac
done

INTERACTIVE=false
[[ -t 0 ]] && INTERACTIVE=true
if _CATALOG_RESULT="$(python3 - "$GLOBAL_ORIGIN" "$SELECTOR" "$LIST_ONLY" "$INTERACTIVE" 3<&0 <<'PY'
import json
import os
import sys
import urllib.error
import urllib.request

origin, selector, list_only, interactive = sys.argv[1:]


def fail(message):
    print(f"clive: {message}", file=sys.stderr)
    raise SystemExit(2)


def valid_text(value):
    return (
        isinstance(value, str)
        and bool(value.strip())
        and not any(ord(character) < 32 or ord(character) == 127 for character in value)
    )


class RejectRedirects(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, request, fp, code, message, headers, new_url):
        raise urllib.error.HTTPError(
            request.full_url,
            code,
            "global catalog redirect refused",
            headers,
            fp,
        )


request = urllib.request.Request(origin + "/v1/models", method="GET")
opener = urllib.request.build_opener(
    urllib.request.ProxyHandler({}), RejectRedirects()
)
try:
    with opener.open(request, timeout=5) as response:
        if response.status < 200 or response.status >= 300:
            fail(f"global catalog returned HTTP {response.status}")
        raw = response.read()
except (OSError, urllib.error.URLError) as error:
    fail(f"global catalog is unreachable: {error}")

try:
    payload = json.loads(raw)
except (UnicodeDecodeError, json.JSONDecodeError) as error:
    fail(f"global catalog is malformed: {error}")
if not isinstance(payload, dict) or not isinstance(payload.get("data"), list):
    fail("global catalog must contain a model data list")
if not payload["data"]:
    fail("global catalog contains no models")

items = []
release_ids = set()
for item in payload["data"]:
    if not isinstance(item, dict) or not valid_text(item.get("id")):
        fail("global catalog contains an invalid release id")
    release_id = item["id"]
    if release_id in release_ids:
        fail(f"global catalog repeats release id {release_id!r}")
    release_ids.add(release_id)
    metadata = item.get("ambix")
    if not isinstance(metadata, dict):
        fail(f"release {release_id!r} has no ambix metadata")
    family = metadata.get("accelerator_family")
    count = metadata.get("accelerator_count")
    precision = metadata.get("checkpoint_precision")
    if not valid_text(family):
        fail(f"release {release_id!r} has an invalid accelerator family")
    if type(count) is not int or count not in {2, 4, 6, 8}:
        fail(f"release {release_id!r} has an invalid accelerator count")
    if not valid_text(precision):
        fail(f"release {release_id!r} has an invalid checkpoint precision")
    max_context = item.get("max_model_len")
    if max_context is not None and (
        type(max_context) is not int or max_context <= 0
    ):
        fail(f"release {release_id!r} has an invalid maximum context")
    topology_selector = f"{release_id}@{count}x{family.lower()}"
    label = f"{release_id} · {count}×{family} · {precision}"
    if max_context is not None:
        label += f" · {max_context // 1024}k ctx"
    items.append(
        {
            "id": release_id,
            "family": family,
            "count": count,
            "precision": precision,
            "max_context": max_context,
            "selector": topology_selector,
            "label": label,
        }
    )

if list_only == "true":
    for item in items:
        print(f'{item["selector"]}\t{item["label"]}')
    raise SystemExit(0)

chosen = None
if selector:
    matches = [
        item
        for item in items
        if selector == item["id"] or selector.lower() == item["selector"].lower()
    ]
    if len(matches) != 1:
        available = ", ".join(item["selector"] for item in items)
        fail(f"selector {selector!r} did not identify one model; available: {available}")
    chosen = matches[0]
elif len(items) == 1:
    chosen = items[0]
elif interactive == "true":
    print("Clive global models:", file=sys.stderr)
    for index, item in enumerate(items, 1):
        print(f"  {index}) {item['label']}", file=sys.stderr)
    print("Select model: ", end="", file=sys.stderr, flush=True)
    with os.fdopen(3) as terminal_input:
        answer = terminal_input.readline().strip()
    try:
        choice = int(answer)
    except ValueError:
        fail("invalid model selection")
    if not 1 <= choice <= len(items):
        fail(f"model selection must be an integer from 1 through {len(items)}")
    chosen = items[choice - 1]
else:
    available = ", ".join(item["selector"] for item in items)
    fail(f"multiple models are available; use --selector ({available})")

print(chosen["id"])
print(chosen["max_context"] or "")
print(chosen["family"])
print(chosen["count"])
print(chosen["precision"])
PY
)"; then
    :
else
    exit $?
fi

if $LIST_ONLY; then
    printf '%s\n' "$_CATALOG_RESULT"
    exit 0
fi

mapfile -t _CATALOG_FIELDS <<< "$_CATALOG_RESULT"
if [[ "${#_CATALOG_FIELDS[@]}" -ne 5 ]]; then
    echo "clive: catalog selection returned invalid data." >&2
    exit 2
fi
MODEL_ID="${_CATALOG_FIELDS[0]}"
MAX_CONTEXT="${_CATALOG_FIELDS[1]}"
ACCELERATOR_FAMILY="${_CATALOG_FIELDS[2]}"
ACCELERATOR_COUNT="${_CATALOG_FIELDS[3]}"
CHECKPOINT_PRECISION="${_CATALOG_FIELDS[4]}"
RUNTIME_LABEL="${ACCELERATOR_COUNT}×${ACCELERATOR_FAMILY} · ${CHECKPOINT_PRECISION}"
CONTEXT_LABEL="unknown"
if [[ -n "$MAX_CONTEXT" ]]; then
    export CLAUDE_CODE_MAX_CONTEXT_TOKENS="$MAX_CONTEXT"
    CONTEXT_LABEL="$(( MAX_CONTEXT / 1024 ))k"
else
    unset CLAUDE_CODE_MAX_CONTEXT_TOKENS
fi

# The global service is anonymous. Harnesses receive a fixed non-secret value
# only because their client configuration requires an API-key variable.
KEY="clive-no-auth"

if [[ "$HARNESS" == "codex" ]]; then
    command -v codex >/dev/null 2>&1 || { echo "clive: 'codex' not on PATH." >&2; exit 127; }
    printf "\nClive (Codex) — serving: %s · %s\n\n" "$MODEL_ID" "$RUNTIME_LABEL" >&2
    OPENAI_BASE_URL="${GLOBAL_ORIGIN}/v1" OPENAI_API_KEY="$KEY" exec codex --model "$MODEL_ID" "${ARGS[@]}"
fi

command -v claude >/dev/null 2>&1 || { echo "clive: 'claude' not on PATH." >&2; exit 127; }

if [[ "$CLIVE_OPENROUTER" != "1" ]]; then
    printf "\nClive — global only — serving: %s · %s\n\n" "$MODEL_ID" "$RUNTIME_LABEL" >&2
    ANTHROPIC_BASE_URL="$GLOBAL_ORIGIN" \
    ANTHROPIC_AUTH_TOKEN="$KEY" \
    ANTHROPIC_API_KEY="" \
    ANTHROPIC_DEFAULT_OPUS_MODEL="$MODEL_ID" \
    ANTHROPIC_DEFAULT_OPUS_MODEL_NAME="$MODEL_ID" \
    ANTHROPIC_DEFAULT_OPUS_MODEL_DESCRIPTION="$RUNTIME_LABEL, $CONTEXT_LABEL ctx" \
    ANTHROPIC_DEFAULT_SONNET_MODEL="$MODEL_ID" \
    ANTHROPIC_DEFAULT_SONNET_MODEL_NAME="$MODEL_ID" \
    ANTHROPIC_DEFAULT_SONNET_MODEL_DESCRIPTION="$RUNTIME_LABEL, $CONTEXT_LABEL ctx" \
    ANTHROPIC_DEFAULT_HAIKU_MODEL="$MODEL_ID" \
    ANTHROPIC_DEFAULT_HAIKU_MODEL_NAME="$MODEL_ID" \
    ANTHROPIC_DEFAULT_HAIKU_MODEL_DESCRIPTION="$RUNTIME_LABEL, $CONTEXT_LABEL ctx" \
    ANTHROPIC_DEFAULT_FABLE_MODEL="$MODEL_ID" \
    ANTHROPIC_DEFAULT_FABLE_MODEL_NAME="$MODEL_ID" \
    ANTHROPIC_DEFAULT_FABLE_MODEL_DESCRIPTION="$RUNTIME_LABEL, $CONTEXT_LABEL ctx" \
    ANTHROPIC_SMALL_FAST_MODEL="$MODEL_ID" \
    ANTHROPIC_MODEL="$MODEL_ID" \
    CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1 \
    exec claude "${ARGS[@]}"
fi

# OpenRouter is reached only by explicit opt-in after global catalog selection.
if [[ -z "$OPENROUTER_NATIVE_RELEASE" ]]; then
    echo "clive: OpenRouter proxy support is not installed; redeploy with 'imas-ambix agent clive PROFILE --openrouter'." >&2
    exit 2
fi
if [[ "$MODEL_ID" != "$OPENROUTER_NATIVE_RELEASE" ]]; then
    echo "clive: selected native release '$MODEL_ID' is not configured in the OpenRouter proxy (configured: '$OPENROUTER_NATIVE_RELEASE'); redeploy the proxy for that release." >&2
    exit 2
fi
if ! systemctl --user is-active --quiet "$LITELLM_SERVICE" 2>/dev/null; then
    echo "clive: starting $LITELLM_SERVICE ..." >&2
    if ! systemctl --user start "$LITELLM_SERVICE" 2>/dev/null; then
        echo "clive: could not start $LITELLM_SERVICE." >&2
        exit 1
    fi
fi

_PROXY_READY=false
for _attempt in $(seq 1 60); do
    (exec 3<>"/dev/tcp/127.0.0.1/$LITELLM_PORT") 2>/dev/null && { exec 3>&- 3<&-; _PROXY_READY=true; break; }
    sleep 0.5
done
if ! $_PROXY_READY; then
    echo "clive: $LITELLM_SERVICE did not become ready." >&2
    exit 1
fi

printf "\nClive — global + OpenRouter — picker: %s, or-opus-4.8, or-sonnet-4.6, or-gpt-5.5, or-glm-5.2\n\n" "$MODEL_ID" >&2
ANTHROPIC_BASE_URL="http://127.0.0.1:$LITELLM_PORT" \
ANTHROPIC_AUTH_TOKEN="clive" \
ANTHROPIC_API_KEY="" \
ANTHROPIC_DEFAULT_HAIKU_MODEL="$MODEL_ID" \
ANTHROPIC_MODEL="$MODEL_ID" \
ANTHROPIC_DEFAULT_HAIKU_MODEL_NAME="$MODEL_ID" \
ANTHROPIC_DEFAULT_HAIKU_MODEL_DESCRIPTION="$RUNTIME_LABEL, $CONTEXT_LABEL ctx" \
ANTHROPIC_DEFAULT_OPUS_MODEL="or-opus-4.8" \
ANTHROPIC_DEFAULT_OPUS_MODEL_NAME="or-opus-4.8" \
ANTHROPIC_DEFAULT_OPUS_MODEL_DESCRIPTION="Claude Opus 4.8 via OpenRouter — frontier" \
ANTHROPIC_DEFAULT_SONNET_MODEL="or-sonnet-4.6" \
ANTHROPIC_DEFAULT_SONNET_MODEL_NAME="or-sonnet-4.6" \
ANTHROPIC_DEFAULT_SONNET_MODEL_DESCRIPTION="Claude Sonnet 4.6 via OpenRouter — balanced" \
ANTHROPIC_DEFAULT_FABLE_MODEL="or-glm-5.2" \
ANTHROPIC_DEFAULT_FABLE_MODEL_NAME="or-glm-5.2" \
ANTHROPIC_DEFAULT_FABLE_MODEL_DESCRIPTION="GLM-5.2 via OpenRouter — open-weight frontier, 1M ctx" \
ANTHROPIC_CUSTOM_MODEL_OPTION="or-gpt-5.5" \
ANTHROPIC_CUSTOM_MODEL_OPTION_NAME="or-gpt-5.5" \
ANTHROPIC_CUSTOM_MODEL_OPTION_DESCRIPTION="GPT-5.5 via OpenRouter — coding model" \
CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1 \
exec claude "${ARGS[@]}"
"""
    return (
        template.replace("__GLOBAL_ORIGIN__", shlex.quote(origin))
        .replace("__OPENROUTER_NATIVE_RELEASE__", shlex.quote(proxy_native_release))
        .replace("__LITELLM_PORT__", str(LITELLM_PORT))
    )
