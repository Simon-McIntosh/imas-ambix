# ruff: noqa: E501 — the module is mostly an embedded bash template; line length
# is governed by the generated shell script, not Python style.
"""Generator for the ``clive`` agent-CLI launcher.

clive points Claude Code (or Codex) at the GPU-served local model, and — when
the user has an OpenRouter key — also exposes OpenRouter models through a
per-user LiteLLM proxy so a single Claude Code session can reach both.

Routing:
  - **No OR key** → direct to the local model (no proxy, instant). The bulk
    SDCC-user path: every user just runs ``clive``.
  - **OR key present** (``~/.config/openrouter/key``) → clive ensures the
    per-user ``imas-ambix-llm`` systemd service is running (idempotent + instant
    when already up — no per-run 10-20 s litellm cold start) and points Claude
    Code at the proxy, which serves ``local`` + ``or-*`` models.

Model picker control (Claude Code 2.1+): when routing via the proxy, clive
launches ``claude --settings '{...}'`` with inline JSON that enables gateway
model discovery (``CLAUDE_CODE_ENABLE_GATEWAY_MODEL_DISCOVERY=1``, so the picker
reads the proxy's ``/v1/models`` with its ``model_info`` descriptions) and an
``availableModels`` allowlist so ONLY the served model + ``or-*`` show — no
haiku, no built-in tiers. ``--settings`` is **session-scoped**: it overrides
per-key for this invocation only and never touches ``~/.claude/settings.json``,
so plain ``claude`` keeps its normal full picker.

Generated from :class:`SiteConfig` and synced repo → ``/work`` on
``imas-ambix agent clive --deploy``. Do not edit the deployed copy.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from imas_ambix.agent.profile import SiteConfig


def generate_clive_script(site: SiteConfig, default_model: str) -> str:
    """Render the ``clive`` launcher for *site* defaulting to *default_model*."""
    from imas_ambix.agent.litellm_service import LITELLM_PORT

    url = site.default_url
    key_file = str(site.api_key_file)
    service = "imas-ambix-llm.service"
    return f'''#!/usr/bin/env bash
# clive — drive an agent CLI against the GPU-served local model (+ OpenRouter).
#
# GENERATED by `imas-ambix agent clive --deploy`. Do not edit in place — edit
# the generator (imas_ambix/agent/clive.py) and re-deploy.
#
# With an OpenRouter key at ~/.config/openrouter/key, clive ensures the per-user
# `{service}` systemd proxy is up (instant when already running) and routes
# local + or-* models through it. Without a key, clive connects directly to the
# local model (no proxy).
#
# Usage:
#   clive [--claude|--codex] [--url URL] [--model NAME] [agent-args...]
#   clive "explain this repo"            # Claude Code (default)
#   clive --codex "write a test"         # OpenAI Codex CLI

set -euo pipefail

# ── Defaults (generated from ambix SiteConfig; override via env or flags) ────
AMBIX_URL="${{AMBIX_AGENT_URL:-{url}}}"
AMBIX_MODEL="${{AMBIX_AGENT_MODEL:-}}"      # empty → auto-detect from /v1/models
AMBIX_KEY_FILE="${{AMBIX_AGENT_KEY_FILE:-{key_file}}}"
LITELLM_PORT="{LITELLM_PORT}"
LITELLM_SERVICE="{service}"
HARNESS="claude"

usage() {{
    cat >&2 <<'USAGE'
clive — drive an agent CLI against the GPU-served local model (+ OpenRouter).

  clive [--claude|--codex] [--url URL] [--model NAME] [agent-args...]

  --claude   Claude Code via the Anthropic Messages API (default).
  --codex    OpenAI Codex CLI via the OpenAI API (local model only).
  --url URL  Local server base URL.   --model NAME  override served model.

With an OpenRouter key (~/.config/openrouter/key) the picker also offers
or-opus-4.8 / or-sonnet-4.6 / or-gpt-5.5 / or-glm-5.2 (routed via a per-user
LiteLLM proxy). Without it, clive uses the local model only.
USAGE
}}

# ── Parse clive's own flags; pass everything else to the agent ───────────────
ARGS=()
while [[ $# -gt 0 ]]; do
    case "$1" in
        --claude) HARNESS="claude"; shift ;;
        --codex)  HARNESS="codex";  shift ;;
        --url)    AMBIX_URL="$2";   shift 2 ;;
        --model)  AMBIX_MODEL="$2"; shift 2 ;;
        -h|--help) usage; exit 0 ;;
        --) shift; ARGS+=("$@"); break ;;
        *)  ARGS+=("$1"); shift ;;
    esac
done

# ── Resolve the local API key (env > file; keyless server → dummy) ───────────
read_key() {{
    if [[ -n "${{AMBIX_AGENT_API_KEY:-}}" ]]; then printf '%s' "$AMBIX_AGENT_API_KEY"; return 0; fi
    [[ -r "$AMBIX_KEY_FILE" ]] || return 0
    local line; line="$(grep -E '^[[:space:]]*AMBIX_AGENT_API_KEY[[:space:]]*=' "$AMBIX_KEY_FILE" | tail -1)"
    [[ -n "$line" ]] || return 0
    line="${{line#*=}}"; line="${{line%\\"}}"; line="${{line#\\"}}"; line="${{line%\\'}}"; line="${{line#\\'}}"
    printf '%s' "$line"
}}
KEY="$(read_key)"; [[ -n "$KEY" ]] || KEY="no-auth"

# ── Do we have an OpenRouter key? (→ enable the proxy + or-* models) ─────────
_HAVE_OR=false
if [[ -n "${{OPENROUTER_API_KEY:-}}" ]] || [[ -r "$HOME/.config/openrouter/key" ]]; then
    _HAVE_OR=true
fi

# ── Resolve the local served model name (no fallback: error if unreachable) ──
if [[ -z "$AMBIX_MODEL" ]]; then
    AMBIX_MODEL="$(curl -sf --max-time 5 -H "Authorization: Bearer $KEY" "$AMBIX_URL/v1/models" 2>/dev/null \\
        | python3 -c "import sys,json; print(json.load(sys.stdin)['data'][0]['id'])" 2>/dev/null || true)"
    if [[ -z "$AMBIX_MODEL" ]]; then
        echo "clive: no model reachable at $AMBIX_URL/v1/models." >&2
        echo "       The serve job is likely down — check: imas-ambix agent status" >&2
        echo "       (or set --model / AMBIX_AGENT_MODEL to bypass the query)." >&2
        exit 1
    fi
fi

# ── Codex: always the local model directly (no proxy, no OR routing) ─────────
if [[ "$HARNESS" == "codex" ]]; then
    command -v codex >/dev/null 2>&1 || {{ echo "clive: 'codex' not on PATH — npm install -g @openai/codex (Node>=18)." >&2; exit 127; }}
    printf "\\nClive (Codex) — serving: %s\\n\\n" "$AMBIX_MODEL" >&2
    OPENAI_BASE_URL="${{AMBIX_URL%/}}/v1" OPENAI_API_KEY="$KEY" exec codex --model "$AMBIX_MODEL" "${{ARGS[@]}}"
fi

command -v claude >/dev/null 2>&1 || {{ echo "clive: 'claude' (Claude Code) not on PATH — https://code.claude.com/download" >&2; exit 127; }}

# ── No OR key → direct local route (everyone's fast path; no proxy) ──────────
if ! $_HAVE_OR; then
    printf "\\nClive — local only — serving: %s\\n\\n" "$AMBIX_MODEL" >&2
    ANTHROPIC_BASE_URL="$AMBIX_URL" \\
    ANTHROPIC_AUTH_TOKEN="$KEY" \\
    ANTHROPIC_API_KEY="" \\
    ANTHROPIC_DEFAULT_OPUS_MODEL="$AMBIX_MODEL" \\
    ANTHROPIC_DEFAULT_SONNET_MODEL="$AMBIX_MODEL" \\
    ANTHROPIC_DEFAULT_HAIKU_MODEL="$AMBIX_MODEL" \\
    ANTHROPIC_MODEL="$AMBIX_MODEL" \\
    CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1 \\
    exec claude "${{ARGS[@]}}"
fi

# ── OR key present → ensure the per-user LiteLLM proxy is up (systemd) ───────
# `systemctl --user start` is idempotent and instant when the unit is already
# active, so we never pay the litellm cold start after the first launch.
if ! systemctl --user is-active --quiet "$LITELLM_SERVICE" 2>/dev/null; then
    echo "clive: starting $LITELLM_SERVICE (first launch — a few seconds) ..." >&2
    if ! systemctl --user start "$LITELLM_SERVICE" 2>/dev/null; then
        echo "clive: could not start $LITELLM_SERVICE." >&2
        echo "       Install it with: imas-ambix agent clive --deploy" >&2
        echo "       Or run clive without an OpenRouter key for local-only." >&2
        exit 1
    fi
fi
# Wait for the proxy to accept connections (cold start bounded; warm = instant).
_OK=false
for _i in $(seq 1 60); do
    (exec 3<>"/dev/tcp/127.0.0.1/$LITELLM_PORT") 2>/dev/null && {{ exec 3>&- 3<&-; _OK=true; break; }}
    sleep 0.5
done
if ! $_OK; then
    echo "clive: $LITELLM_SERVICE did not become ready on 127.0.0.1:$LITELLM_PORT." >&2
    echo "       Check: systemctl --user status $LITELLM_SERVICE; journalctl --user -u $LITELLM_SERVICE" >&2
    exit 1
fi

printf "\\nClive — local + OpenRouter — picker: %s, or-opus-4.8, or-sonnet-4.6, or-gpt-5.5, or-glm-5.2\\n\\n" "$AMBIX_MODEL" >&2

# Point Claude Code at the proxy. The picker is constrained for THIS SESSION
# ONLY via `claude --settings` (inline JSON) — it overrides per-key for this
# invocation and does NOT touch ~/.claude/settings.json, so plain `claude`
# keeps its normal full picker. availableModels (+ enforceAvailableModels) have
# no env-var form, so --settings is the only session-scoped way to set them.
# Gateway discovery makes the picker read the proxy's /v1/models (descriptions);
# the allowlist limits it to the served model + or-* (no haiku, no built-ins).
_CLIVE_SETTINGS="$(cat <<JSON
{{
  "availableModels": ["$AMBIX_MODEL", "or-opus-4.8", "or-sonnet-4.6", "or-gpt-5.5", "or-glm-5.2"],
  "enforceAvailableModels": true,
  "env": {{ "CLAUDE_CODE_ENABLE_GATEWAY_MODEL_DISCOVERY": "1" }}
}}
JSON
)"

ANTHROPIC_BASE_URL="http://127.0.0.1:$LITELLM_PORT" \\
ANTHROPIC_AUTH_TOKEN="clive" \\
ANTHROPIC_API_KEY="" \\
ANTHROPIC_MODEL="$AMBIX_MODEL" \\
ANTHROPIC_DEFAULT_OPUS_MODEL="or-opus-4.8" \\
ANTHROPIC_DEFAULT_SONNET_MODEL="or-sonnet-4.6" \\
ANTHROPIC_DEFAULT_HAIKU_MODEL="$AMBIX_MODEL" \\
CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1 \\
exec claude --settings "$_CLIVE_SETTINGS" "${{ARGS[@]}}"
'''
