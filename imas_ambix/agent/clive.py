# ruff: noqa: E501 — the module is mostly an embedded bash template; line length
# is governed by the generated shell script, not Python style.
"""Generator for the ``clive`` agent-CLI launcher with optional LiteLLM routing.

``clive`` ("CLI + live") points an interactive agent harness at the model
served on the GPU node.  When an `OpenRouter key <~/.config/openrouter/key>`_
is present, it starts a persistent LiteLLM proxy that routes Claude Code tiers:

  - **Default / haiku** → local H200 model (``deepseek-v4-flash``)
  - **Sonnet / opus** → OpenRouter (``claude-sonnet-4.6`` / ``claude-opus-4.8``)
  - Extra OR models: ``gpt-5.5``, ``glm-5.2`` (use ``--model <name>``)

Without an OR key, clive connects directly to the local model (no proxy).

The LiteLLM proxy runs as a **daemon**: it stays alive across ``clive``
invocations.  PID and port are stored in ``~/.cache/clive-litellm.*``.  Kill
it manually with ``pkill -f litellm`` or on logout.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from imas_ambix.agent.profile import SiteConfig


def generate_clive_script(site: SiteConfig, default_model: str) -> str:
    """Render the ``clive`` launcher for *site* defaulting to *default_model*.

    Parameters
    ----------
    site:
        Cluster configuration supplying the URL, key-file path, and group.
    default_model:
        ``served_name`` of the model clive targets by default (the profile
        the operator most recently serves / sets as default).
    """
    url = site.default_url
    key_file = str(site.api_key_file)
    litellm_cfg = str(site.litellm_config_path)
    return f'''#!/usr/bin/env bash
# clive — drive an agent CLI against the GPU-served local model.
#
# GENERATED by `imas-ambix agent clive --deploy`. Do not edit in place — edit
# the generator (imas_ambix/agent/clive.py) and re-deploy.
#
# With an OpenRouter key at ~/.config/openrouter/key, clive starts a persistent
# LiteLLM proxy for tiered routing (local + OR models). Without the key, clive
# connects directly to the local model.
#
# Usage:
#   clive [--claude|--codex] [--url URL] [--model NAME] [agent-args...]
#   clive "explain this repo"            # Claude Code (default)
#   clive --codex "write a test"         # OpenAI Codex CLI

set -euo pipefail

# ── Defaults (generated from ambix SiteConfig; override via env or flags) ────
AMBIX_URL="${{AMBIX_AGENT_URL:-{url}}}"
AMBIX_MODEL="${{AMBIX_AGENT_MODEL:-{default_model}}}"
AMBIX_KEY_FILE="${{AMBIX_AGENT_KEY_FILE:-{key_file}}}"
AMBIX_LITELLM_CONFIG="${{AMBIX_LITELLM_CONFIG:-{litellm_cfg}}}"
HARNESS="claude"

usage() {{
    cat >&2 <<'USAGE'
clive — drive an agent CLI against the GPU-served local model.

  clive [--claude|--codex] [--url URL] [--model NAME] [agent-args...]

  --claude        Use Claude Code via the Anthropic Messages API (default).
  --codex         Use the OpenAI Codex CLI via the OpenAI API.
  --url URL       Server base URL.
  --model NAME    Served model name.
  -h, --help      Show this help.

With an OpenRouter key (see ~/.config/openrouter/key), clive routes tiers:
  Default / haiku → local H200  ·  Sonnet / opus → OpenRouter
  Extra: --model gpt-5.5  ·  --model glm-5.2

Env overrides: AMBIX_AGENT_URL, AMBIX_AGENT_MODEL, AMBIX_AGENT_KEY_FILE,
AMBIX_AGENT_API_KEY, AMBIX_LITELLM_CONFIG.
USAGE
}}

# ── Parse clive's own flags; pass everything else to the agent ───────────────
ARGS=()
while [[ $# -gt 0 ]]; do
    case "$1" in
        --claude) HARNESS="claude"; shift ;;
        --codex)  HARNESS="codex";  shift ;;
        --url)    AMBIX_URL="$2";   shift 2 ;;
        --model)  AMBIX_MODEL="$2"; shift 2 ;;
        -h|--help) usage; exit 0 ;;
        --) shift; ARGS+=("$@"); break ;;
        *)  ARGS+=("$1"); shift ;;
    esac
done

# ── Resolve the API key (env > file) without echoing it ──────────────────────
read_key() {{
    if [[ -n "${{AMBIX_AGENT_API_KEY:-}}" ]]; then
        printf '%s' "$AMBIX_AGENT_API_KEY"; return 0
    fi
    [[ -r "$AMBIX_KEY_FILE" ]] || return 0
    local line
    line="$(grep -E '^[[:space:]]*AMBIX_AGENT_API_KEY[[:space:]]*=' "$AMBIX_KEY_FILE" | tail -1)"
    [[ -n "$line" ]] || return 0
    line="${{line#*=}}"
    line="${{line%\\"}}"; line="${{line#\\"}}"
    line="${{line%\\'}}"; line="${{line#\\'}}"
    printf '%s' "$line"
}}

KEY="$(read_key)"
[[ -n "$KEY" ]] || KEY="no-auth"

# ── OpenRouter key check & LiteLLM daemon ────────────────────────────────────
# Without an OR key, connect directly to the local model (no proxy).
_USE_PROXY=false
_OR_KEY=""

if [[ -n "${{OPENROUTER_API_KEY:-}}" ]]; then
    _OR_KEY="$OPENROUTER_API_KEY"
elif [[ -r "$HOME/.config/openrouter/key" ]]; then
    _OR_KEY="$(tr -d '[:space:]' < "$HOME/.config/openrouter/key")"
fi

if [[ -n "$_OR_KEY" ]]; then
    _USE_PROXY=true
    _CACHE_DIR="$HOME/.cache"
    _PID_FILE="$_CACHE_DIR/clive-litellm.pid"
    _PORT_FILE="$_CACHE_DIR/clive-litellm.port"
    _LOG_FILE="$_CACHE_DIR/clive-litellm.log"

    # Check if existing daemon is still alive
    _DAEMON_ALIVE=false
    if [[ -f "$_PID_FILE" ]] && [[ -f "$_PORT_FILE" ]]; then
        _OLD_PID="$(cat "$_PID_FILE" 2>/dev/null || echo "")"
        _OLD_PORT="$(cat "$_PORT_FILE" 2>/dev/null || echo "")"
        if [[ -n "$_OLD_PID" ]] && kill -0 "$_OLD_PID" 2>/dev/null; then
            # Quick health check
            if curl -sf --max-time 2 "http://127.0.0.1:$_OLD_PORT/health/ready" >/dev/null 2>&1; then
                _DAEMON_ALIVE=true
                LITELLM_PORT="$_OLD_PORT"
            fi
        fi
    fi

    if ! $_DAEMON_ALIVE; then
        # Start a new daemon
        command -v litellm >/dev/null 2>&1 || {{
            echo "clive: 'litellm' not on PATH (pip/uv install litellm) — needed for routing." >&2
            exit 127
        }}
        [[ -r "$AMBIX_LITELLM_CONFIG" ]] || {{
            echo "clive: routing config not found: $AMBIX_LITELLM_CONFIG (run: imas-ambix agent clive --deploy)" >&2
            exit 1
        }}

        export OPENROUTER_API_KEY="$_OR_KEY"
        AMBIX_LOCAL_KEY="$KEY"

        LITELLM_PORT="$(python3 -c 'import socket;s=socket.socket();s.bind(("127.0.0.1",0));print(s.getsockname()[1]);s.close()')"
        export LITELLM_PORT

        litellm --config "$AMBIX_LITELLM_CONFIG" --host 127.0.0.1 --port "$LITELLM_PORT" > "$_LOG_FILE" 2>&1 &
        _LPID=$!
        echo "$_LPID" > "$_PID_FILE"
        echo "$LITELLM_PORT" > "$_PORT_FILE"

        # Wait for readiness (up to 20 s)
        _OK=false
        for _i in $(seq 1 40); do
            (exec 3<>"/dev/tcp/127.0.0.1/$LITELLM_PORT") 2>/dev/null && {{ exec 3>&- 3<&-; _OK=true; break; }}
            kill -0 "$_LPID" 2>/dev/null || {{ echo "clive: LiteLLM failed to start:" >&2; tail -8 "$_LOG_FILE" >&2; exit 1; }}
            sleep 0.5
        done
        if ! $_OK; then
            echo "clive: LiteLLM did not become ready within 20 s." >&2
            tail -5 "$_LOG_FILE" >&2
            exit 1
        fi
        echo "clive: LiteLLM daemon started (pid $_LPID, port $LITELLM_PORT)." >&2
    fi
fi

# ── Launch the chosen harness ────────────────────────────────────────────────
case "$HARNESS" in
    claude)
        if ! command -v claude >/dev/null 2>&1; then
            echo "clive: 'claude' (Claude Code) not on PATH — install it per-user:" >&2
            echo "       https://code.claude.com/download" >&2
            exit 127
        fi

        if $_USE_PROXY; then
            # Via LiteLLM proxy — tiered routing
            echo "clive: router active — Default/haiku→local, Sonnet/Op→OR." >&2
            ANTHROPIC_BASE_URL="http://127.0.0.1:$LITELLM_PORT" \\
            ANTHROPIC_AUTH_TOKEN="clive" \\
            ANTHROPIC_MODEL="local" \\
            ANTHROPIC_DEFAULT_OPUS_MODEL="opus" \\
            ANTHROPIC_DEFAULT_SONNET_MODEL="sonnet" \\
            ANTHROPIC_DEFAULT_HAIKU_MODEL="haiku" \\
            CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1 \\
            exec claude "${{ARGS[@]}}"
        else
            # Direct — all tiers to the one local model
            ANTHROPIC_BASE_URL="$AMBIX_URL" \\
            ANTHROPIC_AUTH_TOKEN="$KEY" \\
            ANTHROPIC_API_KEY="" \\
            ANTHROPIC_DEFAULT_OPUS_MODEL="$AMBIX_MODEL" \\
            ANTHROPIC_DEFAULT_SONNET_MODEL="$AMBIX_MODEL" \\
            ANTHROPIC_DEFAULT_HAIKU_MODEL="$AMBIX_MODEL" \\
            ANTHROPIC_MODEL="$AMBIX_MODEL" \\
            CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1 \\
            exec claude "${{ARGS[@]}}"
        fi
        ;;
    codex)
        if ! command -v codex >/dev/null 2>&1; then
            echo "clive: 'codex' (Codex CLI) not on PATH — install it per-user:" >&2
            echo "       npm install -g @openai/codex   (needs Node >= 18)" >&2
            exit 127
        fi
        # Codex always connects directly (no proxy).
        OPENAI_BASE_URL="${{AMBIX_URL%/}}/v1" \\
        OPENAI_API_KEY="$KEY" \\
        exec codex --model "$AMBIX_MODEL" "${{ARGS[@]}}"
        ;;
    *)
        echo "clive: unknown harness '$HARNESS'" >&2; exit 2 ;;
esac
'''
